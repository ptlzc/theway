fn typescript(schemas: &[(&str, Value)]) -> Result<String, serde_json::Error> {
    let mut hasher = Sha256::new();
    for (path, schema) in schemas {
        hasher.update(path.as_bytes());
        hasher.update(serde_json::to_vec(schema)?);
    }
    let fingerprint = hex::encode(hasher.finalize());
    Ok(format!(
        "// @generated by `cargo run -p theway-contract --example generate_extension_artifacts -- <output-dir>`\n// ABI schema sha256: {fingerprint}\n{TYPESCRIPT_DECLARATIONS}"
    ))
}

