pub fn generate(output_dir: &Path) -> Result<(), Box<dyn std::error::Error>> {
    let schemas = schema_documents()?;
    fs::create_dir_all(output_dir.join("schemas"))?;
    for (relative_path, schema) in &schemas {
        let mut encoded = serde_json::to_string_pretty(schema)?;
        encoded.push('\n');
        fs::write(output_dir.join(relative_path), encoded)?;
    }
    fs::write(
        output_dir.join("theway-extension.d.ts"),
        typescript(&schemas)?,
    )?;
    Ok(())
}

